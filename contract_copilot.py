def generate_official_eot_letter(
    project_name: str,
    contract_ref: str,
    client_name: str,
    contractor_name: str,
    claimed_days: int,
    reasons_list: List[str],
    prolongation_cost_str: str,
    letter_date: str = None
) -> str:
    """توليد كتاب رسمي عراقي للمطالبة بتمديد مدة العقد والتعويض المالي وفق المادة 44"""
    if not letter_date:
        letter_date = datetime.now().strftime("%Y/%m/%d")

    reasons_bullets = "\n".join([f"  {idx+1}. {r}" for idx, r in enumerate(reasons_list)])

    letter = f"""
الجمهورية العراقية
{client_name}
دائرة المهندس المقيم / إدارة المشروع

العدد: م.ع / {contract_ref} / 2026
التاريخ: {letter_date} م

إلى / {client_name} - مكتب السيد المدير العام المحترم
م / طلب تمديد مدة الإكمال والمطالبة بالتعويض المالي (EOT Claim)

تحية طيبة وتـقـديـر ...

إشارة إلى العقد المرقم ({contract_ref}) الخاص بمشروع ({project_name})، واستناداً إلى أحكام **المادة (44) [تمديد مدة الإكمال]** و **المادة (60) [السلف والدفعات]** من الشروط العامة لمقاولات أعمال الهندسة المدنية (الجزء الأول):

نود إعلام سيادتكم بأن سير الأعمال في المشروع قد واجه توقفات وتأخيرات جوهرية ناتجة عن أسباب تعاقدية خارجة عن إرادة وسيطرة المقاول، والموجزة أدناه:
{reasons_bullets}

وحيث أن هذه التوقفات قد أثرت تأثيراً مباشراً على الأنشطة الواقعة على المسار الحرج (Critical Path)، فإننا نلتمس من سيادتكم التفضل بالموافقة على:
1. منحنا تمديداً رسمياً لمدة العقد مقداره **({claimed_days}) يوماً تقويمياً**، مع تعديل تاريخ الإنجاز النهائي وفقاً لذلك.
2. تعويض المقاول عن تكاليف استمرار الموقع والمصاريف الإدارية غير المباشرة المترتبة خلال فترة التأخير بمبلغ إجمالي قدره **({prolongation_cost_str})** استناداً لأحكام العقد.

مرفق طياً: كشف التحليل الزمني للمسار الحرج (CPM Schedule Analysis) وجداول احتساب تكاليف الاستمرار.

شاكرين تعاونكم ودعمكم المستمر لإنجاح المشروع في خدمة الصالح العام.

وتفضلوا بقبول فائق التقدير والاحترام ...


نسخة منه إلى:
• المهندس المقيم / للمتابعة والتدقيق الفني.
• الدائرة القانونية والمالية.
• الأرشيف والأوليات.

--------------------------------------------------
مدير المشروع / ممثل شركة ({contractor_name})
التوقيع: ............................
"""
    return letter.strip()

def generate_coordination_rfi_letter(
    project_name: str,
    contract_ref: str,
    client_name: str,
    issue_code: str,
    issue_desc: str,
    proposed_solution: str,
    letter_date: str = None
) -> str:
    """توليد كتاب طلب حسم تعارضات التنسيق الفني والموقعي (BIM / Coordination RFI)"""
    if not letter_date:
        letter_date = datetime.now().strftime("%Y/%m/%d")

    letter = f"""
الجمهورية العراقية
مشروع: {project_name}
إدارة التنسيق والنمذجة الهندسية (BIM Coordination Office)

العدد: RFI / {issue_code} / 2026
التاريخ: {letter_date} م

إلى / دائرة المهندس المقيم المحترم
م / طلب حسم تعارض تنسيقي موقعي وتزويدنا بالمخططات التنفيذية (RFI)

تحية طيبة ...

أثناء مراجعة وتدقيق المخططات التنفيذية وتطابقها مع واقع الموقع في مشروع ({project_name})، رصد فريق التنسيق والنمذجة التعارض الفني الآتي:

• **رمز التعارض:** {issue_code}
• **وصف التعارض:** {issue_desc}
• **الحل الهندسي المقترح (ISO 31000):** {proposed_solution}

نرجو التفضل بالاطلاع والتوجيه بحسم التعارض والمصادقة على التعديل المقترح أو تزويدنا بالمخطط التعديلي المعتمد خلال مدة أقصاها (7) أيام لتفادي توقف المسار الحرج للأنشطة المرتبطة.

شاكرين حسن تعاونكم ...

--------------------------------------------------
مهندس التنسيق والـ BIM الموقعي
التوقيع: ............................
"""
    return letter.strip()

def generate_coordination_meeting_minutes(
    project_name: str,
    issues_summary: List[Dict[str, Any]],
    meeting_date: str = None
) -> str:
    """توليد محضر اجتماع ورشة التنسيق الفني ISO 31000 الرسمي"""
    if not meeting_date:
        meeting_date = datetime.now().strftime("%Y/%m/%d")

    issues_text = ""
    for idx, iss in enumerate(issues_summary):
        issues_text += f"""
{idx+1}. **التعارض ({iss.get('id')}):** {iss.get('title_ar')}
   - الجهة المسؤولة عن التنفيذ: {iss.get('responsible_party', 'المهندس المقيم والمقاول')}
   - الإجراء المتفق عليه: {iss.get('treatment_action_ar', 'تعديل المسار والتثبيت قبل الصب')}
"""

    doc = f"""
جمهورية العراق
دائرة المهندس المقيم / الجهة المستفيدة
مشروع: {project_name}

محضر اجتماع ورشة التنسيق الموقعي وحسم التعارضات (ISO 31000 Workshop)
===================================================================
التاريخ: {meeting_date} م
المكان: قاعة الاجتماعات في دائرة المهندس المقيم بالموقع

الحضور:
1. رئيس وأعضاء دائرة المهندس المقيم.
2. مدير المشروع ومدير المكتب الفني للمقاول.
3. ممثلو الدوائر الخدمية والجهات ذات العلاقة.

جدول الأعمال:
مراجعة مصفوفة التعارضات وتطبيق استراتيجيات المعالجة وفق معيار إدارة المخاطر الدولي ISO 31000.

القرارات والتوصيات المتخذة:
{issues_text}

تم الاتفاق على أن يتم تنفيذ كافة الإجراءات المذكورة أعلاه وفق التوقيتات المحددة لتأمين الجدول الزمني للمشروع.

التواقيع:
• ممثل رب العمل: ............................
• المهندس المقيم: ............................
• مدير مشروع المقاول: ............................
"""
    return doc.strip()
